#!/bin/bash
# Полная миграция radiodetali: Timeweb → Selectel
# Запускать по шагам вручную (см. комментарии ниже)
set -euo pipefail

cat << 'EOF'

╔══════════════════════════════════════════════════════════════╗
║  Миграция radiodetali: Timeweb → Selectel                    ║
╚══════════════════════════════════════════════════════════════╝

ВАЖНО: проблема с мобильной связью связана с фильтрацией доменных
имён операторами (ТСПУ), а не с хостингом. Полный перенос может
не изменить доступность с мобильного — но бэкап и перенос всё равно
нужны для отказа от Timeweb.

────────────────────────────────────────────────────────────────
ШАГ 1. Бэкап на Timeweb (212.60.21.10)
────────────────────────────────────────────────────────────────

  ssh root@212.60.21.10

  cd ~/app
  # Скопируйте scripts/backup-server.sh на сервер или выполните вручную:
  bash scripts/backup-server.sh

  # Скачайте архив на свой компьютер:
  # scp root@212.60.21.10:~/radiodetali-backup-*.tar.gz .

────────────────────────────────────────────────────────────────
ШАГ 2. Подготовка Selectel (139.100.216.41)
────────────────────────────────────────────────────────────────

  ssh root@139.100.216.41

  # Клонируйте репозиторий или скопируйте папку deploy/selectel:
  git clone https://github.com/vjf2g46p6j-cloud/radiodetali.git ~/radiodetali-src
  cd ~/radiodetali-src
  bash deploy/selectel/setup-server.sh

  # Загрузите бэкап (с локального ПК):
  # scp radiodetali-backup-*.tar.gz root@139.100.216.41:~/

────────────────────────────────────────────────────────────────
ШАГ 3. Восстановление данных
────────────────────────────────────────────────────────────────

  ssh root@139.100.216.41
  cd ~/radiodetali-src
  bash scripts/restore-selectel.sh ~/radiodetali-backup-*.tar.gz

  # Проверка приложения:
  curl -s -o /dev/null -w "HTTP %{http_code}\n" http://127.0.0.1:3050
  docker compose -f ~/app/docker-compose.yml ps

────────────────────────────────────────────────────────────────
ШАГ 4. Переключение nginx (убрать прокси на Timeweb)
────────────────────────────────────────────────────────────────

  cd ~/radiodetali-src
  bash deploy/selectel/setup-nginx.sh

  # Проверка с сервера:
  curl -I https://драгсоюз.рф
  curl -I https://dragsoyuz.ru

────────────────────────────────────────────────────────────────
ШАГ 5. Проверка перед отключением Timeweb
────────────────────────────────────────────────────────────────

  □ Главная страница открывается
  □ Каталог и карточки товаров работают
  □ Картинки (uploads) отображаются
  □ Админка /admin открывается
  □ Заказы/формы работают

  DNS уже указывает на 139.100.216.41 — менять не нужно.

────────────────────────────────────────────────────────────────
ШАГ 6. Отключение Timeweb (после успешной проверки)
────────────────────────────────────────────────────────────────

  ssh root@212.60.21.10
  cd ~/app && docker compose down

  Остановите VPS в панели Timeweb.

────────────────────────────────────────────────────────────────
Рекомендации по серверу Selectel
────────────────────────────────────────────────────────────────

  Текущий тариф (1 vCPU / 1 GB / 5 GB) — минимальный.
  Для стабильной работы PostgreSQL + Next.js рекомендуется:
    • RAM: 2 GB (минимум)
    • Диск: 20+ GB (uploads + Docker + БД)

  Увеличить тариф можно в панели Selectel без смены IP.

EOF
